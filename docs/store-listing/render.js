#!/usr/bin/env node
/**
 * Render listings.json into ready-to-paste text files.
 *
 * Why this exists: listings.json is JSON, so its line breaks are stored as the
 * two characters \n. Copying a description straight out of the JSON pastes
 * literal "\n" into the store dashboard instead of real line breaks. These
 * .txt files carry real line breaks, so you can select and paste each field.
 *
 * The files are GENERATED. listings.json is the only place to edit — the
 * previous hand-maintained copies drifted three months behind and still
 * contained claims we had already removed (timezone delivery, "Claude-powered",
 * free=50/mo, Starter=2,000/mo). `node docs/store-listing/check-limits.js`
 * fails if they fall out of sync again.
 *
 * Run: node docs/store-listing/render.js
 */
const fs = require("fs");
const path = require("path");

const DIR = __dirname;
const OUT = path.join(DIR, "descriptions");
const listings = JSON.parse(fs.readFileSync(path.join(DIR, "listings.json"), "utf8"));

const TITLE_MAX = 45;
const SUMMARY_MAX = 132;
const len = (s) => [...s].length;

function render(lang, entry) {
  const bar = "=".repeat(64);
  return [
    `${bar}`,
    `GENERATED from listings.json — do not edit this file.`,
    `Language: ${lang}`,
    `Copy each block below into the store dashboard field of the same name.`,
    `${bar}`,
    ``,
    `--- TITLE (${len(entry.title)}/${TITLE_MAX} characters) ---`,
    entry.title,
    ``,
    `--- SUMMARY / SHORT DESCRIPTION (${len(entry.summary)}/${SUMMARY_MAX} characters) ---`,
    entry.summary,
    ``,
    `--- DESCRIPTION (${len(entry.description)} characters) ---`,
    entry.description,
    ``,
  ].join("\n");
}

function writeAll() {
  const generated = new Set();
  if (!fs.existsSync(OUT)) fs.mkdirSync(OUT, { recursive: true });

  for (const [lang, entry] of Object.entries(listings)) {
    // No BOM: the header lines above absorb any leading-character weirdness,
    // so a stray invisible byte can never end up inside a copied title.
    fs.writeFileSync(path.join(OUT, `${lang}.txt`), render(lang, entry), "utf8");
    generated.add(`${lang}.txt`);
    console.log(`  + descriptions/${lang}.txt`);
  }

  const leftovers = fs
    .readdirSync(OUT)
    .filter((f) => f.endsWith(".txt") && !generated.has(f));
  if (leftovers.length) {
    console.log(`\n  ! stale files with no entry in listings.json: ${leftovers.join(", ")}`);
    console.log(`    (delete them, or add the language to listings.json)`);
  }

  console.log(`\n${generated.size} file(s) rendered from listings.json.`);
}

// Only write when run directly — check-limits.js imports render() to compare.
if (require.main === module) writeAll();

module.exports = { render, writeAll };
